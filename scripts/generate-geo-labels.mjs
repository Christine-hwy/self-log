// Dev-time generation script. Run manually with:
//   node scripts/generate-geo-labels.mjs
//
// Reads the `world-countries` and `all-the-cities` devDependencies (never
// shipped to the browser bundle) and writes a small static, committed
// TypeScript data file at src/data/geoLabels.ts containing only the fields
// GlobeView.tsx needs. This script is NOT part of `npm run build`.

import countries from 'world-countries';
import cities from 'all-the-cities';
import { writeFileSync } from 'fs';

function tierForPopulation(population) {
  if (population >= 5_000_000) return 'tier1';
  if (population >= 1_000_000) return 'tier2';
  if (population >= 300_000) return 'tier3';
  return null;
}

const countryLabels = countries
  .filter((c) => c.independent === true && Array.isArray(c.latlng) && c.latlng.length === 2)
  .map((c) => ({
    kind: 'country',
    name: c.name.common,
    lat: c.latlng[0],
    lng: c.latlng[1],
  }));

const cityLabels = cities
  .map((c) => {
    if (typeof c.population !== 'number' || !c.loc || !Array.isArray(c.loc.coordinates)) {
      return null;
    }
    const tier = tierForPopulation(c.population);
    if (!tier) return null;
    return {
      kind: 'city',
      name: c.name,
      lat: c.loc.coordinates[1],
      lng: c.loc.coordinates[0],
      population: c.population,
      tier,
    };
  })
  .filter(Boolean);

const output = `// AUTO-GENERATED by scripts/generate-geo-labels.mjs. Do not hand-edit.
// Regenerate with: node scripts/generate-geo-labels.mjs

export type GeoLabelKind = 'country' | 'city';
export type CityTier = 'tier1' | 'tier2' | 'tier3';

export interface GeoLabel {
  kind: GeoLabelKind;
  name: string;
  lat: number;
  lng: number;
  population?: number;
  tier?: CityTier;
}

export const geoLabels: GeoLabel[] = ${JSON.stringify([...countryLabels, ...cityLabels], null, 2)};
`;

writeFileSync('src/data/geoLabels.ts', output);

const tierCounts = cityLabels.reduce((acc, c) => {
  acc[c.tier] = (acc[c.tier] || 0) + 1;
  return acc;
}, {});

console.log(`Generated ${countryLabels.length} countries and ${cityLabels.length} cities.`);
console.log('City tier breakdown:', tierCounts);
